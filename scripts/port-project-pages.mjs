import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const gatsbyRoot = path.resolve(root, "..", "virtual-building-studio");
const projectsDir = path.join(gatsbyRoot, "src", "pages", "projects");
const portfolioDir = path.join(gatsbyRoot, "src", "pages", "portfolio");
const portoflioDir = path.join(gatsbyRoot, "src", "pages", "portoflio");
const outDir = path.join(root, "src", "components", "vbs", "projects", "pages");
const sharedDir = path.join(root, "src", "components", "vbs", "projects", "hvac-case");
const registryPath = path.join(root, "src", "lib", "project-pages-registry.ts");

fs.mkdirSync(outDir, { recursive: true });
fs.mkdirSync(sharedDir, { recursive: true });

function readIfExists(filePath) {
  return fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : null;
}

function resolveProjectSource(slug) {
  const projectFile = path.join(projectsDir, `${slug}.js`);
  let content = readIfExists(projectFile);
  if (!content) return null;

  const portfolioImport = content.match(/from "\.\.\/portfolio\/([^"]+)"/);
  const portoflioImport = content.match(/from "\.\.\/portoflio\/([^"]+)"/);

  if (portfolioImport || portoflioImport) {
    const rel = (portfolioImport || portoflioImport)[1].replace(/\.js$/, "");
    const folder = portoflioImport ? portoflioDir : portfolioDir;
    const resolved = readIfExists(path.join(folder, `${rel}.js`));
    if (resolved) content = resolved;
  }

  return content;
}

function transformSource(content, slug) {
  let code = content.replace(/\r\n/g, "\n");

  code = code.replace(/^import Seo from.*\n/gm, "");
  code = code.replace(/^import \{[^}]*Meta[^}]*\} from.*metaData.*\n/gm, "");
  code = code.replace(/export const Head = \(\) => \([\s\S]*?\);\n\n/g, "");
  code = code.replace(/export const Head = \(\) => \([\s\S]*?\);\n/g, "");

  code = code.replace(/import Header from.*\n/g, "");
  code = code.replace(/import Footer from.*\n/g, "");
  code = code.replace(/import Contact from.*\n/g, "");
  code = code.replace(/import BookMeetingCta from.*\n/g, 'import BookMeetingCta from "@/components/vbs/book-meeting-cta";\n');

  code = code.replace(/<div className="light-header">\s*<Header \/>\s*<\/div>/g, "");
  code = code.replace(/<Header \/>\s*/g, "");
  code = code.replace(/<Footer \/>\s*/g, "");
  code = code.replace(/<Contact[^>]*\/>\s*/g, "");
  code = code.replace(/<BookMeetingCta[^>]*\/>\s*/g, "");

  code = code.replace(
    /from "\.\/mepf-bim-coordination-for-industrial-office-building"/g,
    'from "@/components/vbs/projects/hvac-case/shared"',
  );
  code = code.replace(
    /from "\.\.\/\.\.\/components\/vbs-redesign\/utils\/nimbus-booking"/g,
    'from "@/utils/nimbus-booking"',
  );
  code = code.replace(
    /from "\.\.\/\.\.\/components\/vbs-redesign\/utils\/nimbus-booking\.js"/g,
    'from "@/utils/nimbus-booking"',
  );

  code = code.replace(/import \{ Link \} from "gatsby";/g, 'import Link from "next/link";');
  code = code.replace(/\bto=/g, "href=");

  code = code.replace(
    /import ([A-Za-z][\w]*) from "\.\.\/\.\.\/\.\.\/static\/(image|icon)\/([^"]+)";/g,
    'const $1 = "/$2/$3";',
  );

  if (!code.includes('"use client"')) {
    code = `"use client";\n// @ts-nocheck\n\n${code}`;
  }

  return code;
}

function extractHvacShared() {
  const mepfPath = path.join(projectsDir, "mepf-bim-coordination-for-industrial-office-building.js");
  const raw = fs.readFileSync(mepfPath, "utf8");
  const pageStart = raw.indexOf("function MepfBimCoordinationForIndustrialOfficeBuildingPage");
  const stylesMarker = "/* All page styles scoped to .hvac-case";
  const stylesStart = raw.indexOf(stylesMarker);
  const defaultExport = raw.lastIndexOf("export default");

  const sharedHead = raw.slice(0, pageStart);
  const sharedStyles = raw.slice(stylesStart, defaultExport);

  let shared = `${sharedHead}\n${sharedStyles}`;
  shared = transformSource(shared, "shared");
  shared = shared.replace(/export default[\s\S]*$/g, "");

  fs.writeFileSync(path.join(sharedDir, "shared.tsx"), shared, "utf8");
}

extractHvacShared();

const slugs = fs
  .readdirSync(projectsDir)
  .filter((name) => name.endsWith(".js"))
  .map((name) => name.replace(/\.js$/, ""));

const registryEntries = [];

for (const slug of slugs) {
  const source = resolveProjectSource(slug);
  if (!source) continue;

  const transformed = transformSource(source, slug);
  const outFile = path.join(outDir, `${slug}.tsx`);
  fs.writeFileSync(outFile, transformed, "utf8");
  registryEntries.push(slug);
  console.log(`ported ${slug}`);
}

const registry = `// Auto-generated by scripts/port-project-pages.mjs — do not edit manually.
export const projectPageSlugs = ${JSON.stringify(registryEntries, null, 2)} as const;

export type ProjectPageSlug = (typeof projectPageSlugs)[number];

export async function loadProjectPage(slug: string) {
  switch (slug) {
${registryEntries
  .map(
    (slug) =>
      `    case "${slug}":\n      return import("@/components/vbs/projects/pages/${slug}");`,
  )
  .join("\n")}
    default:
      return null;
  }
}
`;

fs.writeFileSync(registryPath, registry, "utf8");
console.log(`Registry: ${registryEntries.length} pages`);
